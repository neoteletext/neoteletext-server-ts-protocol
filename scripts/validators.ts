// Compiles the server's published schema (schema/protocol-7.json, the
// server's protocol/schema-7.json, generated from its Rust types) into
// plain validation functions with Ajv's standalone mode (DEC-1482 item 7):
// nothing compiles a schema when a program runs, so the kit runs where
// code generation at run time is not allowed. The functions are written to
// src/wire/generated/, which is built here, never edited, never committed.
//   node scripts/validators.ts

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const ROOT = join(import.meta.dirname, "..");
const SCHEMA = join(ROOT, "schema", "protocol-7.json");
const OUT = join(ROOT, "src", "wire", "generated");
/** The name the schema is known by, for the references below. */
const SCHEMA_ID = "protocol";

const schema: unknown = JSON.parse(readFileSync(SCHEMA, "utf8"));
const ajv = new Ajv2020({
  code: { source: true, esm: true },
  strict: true,
  // The schema's nullable fields are a type and "null" (schemars' Option).
  allowUnionTypes: true,
  // The schema's integer formats name the Rust type; their minimum and maximum carry every bound, so each format is known and checks nothing more.
  formats: { uint8: true, uint16: true, uint32: true, uint64: true, int16: true },
});
ajv.addSchema(schema as object, SCHEMA_ID);

/** Each message of a union by its `type`: one validator a message, so a fault is reported against the message it is in, not against every other. */
function branches(union: string): Map<string, string> {
  const definitions = (
    schema as {
      readonly $defs: Readonly<Record<string, { readonly oneOf: readonly { readonly properties: { readonly type: { readonly const: string } } }[] }>>;
    }
  ).$defs;
  const found = new Map<string, string>();
  definitions[union]?.oneOf.forEach((branch, index) => {
    found.set(branch.properties.type.const, `${SCHEMA_ID}#/$defs/${union}/oneOf/${index}`);
  });
  if (found.size === 0) {
    throw new Error(`the schema has no ${union}`);
  }
  return found;
}
const program = branches("ProgramMessage");
const server = branches("ServerMessage");
const exported: Record<string, string> = {};
for (const [prefix, union] of [
  ["program", program],
  ["server", server],
] as const) {
  for (const [type, reference] of union) {
    exported[`${prefix}_${type}`] = reference;
  }
}
const named = (prefix: string, union: ReadonlyMap<string, string>): string =>
  `{ ${[...union.keys()].map((type) => `${JSON.stringify(type)}: ${prefix}_${type}`).join(", ")} }`;
const code = `${standaloneCode(ajv, exported)}\nexport const program = ${named("program", program)};\nexport const server = ${named("server", server)};\n`;

/**
 * Ajv's standalone code takes two helpers from Ajv's runtime with
 * `require`, even as a module: a string's length in code points, and deep
 * equality of JSON values for `const` and `enum`. They are written here in
 * their place, so the release needs nothing of Ajv when it runs.
 */
const RUNTIME: Readonly<Record<string, string>> = {
  ucs2length: "function (text) { let length = 0; for (const _ of text) { length += 1; } return length; }",
  equal:
    'function equal(one, two) { if (one === two) { return true; } if (typeof one !== "object" || typeof two !== "object" || one === null || two === null || Array.isArray(one) !== Array.isArray(two)) { return false; } const keys = Object.keys(one); return keys.length === Object.keys(two).length && keys.every((key) => Object.hasOwn(two, key) && equal(one[key], two[key])); }',
};
const linked = code.replaceAll(/require\("ajv\/dist\/runtime\/([a-z0-9]+)"\)\.default/gu, (_, name: string) => {
  const helper = RUNTIME[name];
  if (helper === undefined) {
    throw new Error(`the validators need Ajv's runtime ${name}, which scripts/validators.ts does not write`);
  }
  return `(${helper})`;
});
if (linked.includes("require(")) {
  throw new Error("the validators still require a module");
}

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "validators.js"), `// Generated by scripts/validators.ts from schema/protocol-7.json: never edit.\n${linked}`);
writeFileSync(
  join(OUT, "validators.d.ts"),
  `// Generated by scripts/validators.ts from schema/protocol-7.json: never edit.
/** One fault Ajv found. */
export interface ValidationFault {
  readonly instancePath: string;
  readonly keyword: string;
  readonly params: Readonly<Record<string, unknown>>;
  readonly message?: string;
}
/** A validator: true for a valid value, with its faults on \`errors\` otherwise. */
export interface Validator {
  (value: unknown): boolean;
  errors?: readonly ValidationFault[] | null;
}
/** Each message a program sends, by its \`type\`: the schema's $defs/ProgramMessage. */
export declare const program: Readonly<Record<string, Validator>>;
/** Each message the server sends, by its \`type\`: the schema's $defs/ServerMessage. */
export declare const server: Readonly<Record<string, Validator>>;
`,
);
