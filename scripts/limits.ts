// Writes src/rules/limits.ts, the limits of a page's rule table, from the
// engine's crates/neoteletext-rules/src/limits.rs, their one home
// (page-rules.md RULE-57, REQ-6608: "a kit may carry a generated copy
// checked against it"). Each constant of the file's RULE_57 table, and
// TICKS_PER_SECOND, the table's last line, keeps the engine's name, its
// value as the engine writes it and its comment.
//   node scripts/limits.ts LIMITS_RS           write the file
//   node scripts/limits.ts LIMITS_RS --check   fail when the file differs
// scripts/check.sh gives it the engine's file at the commit LIMITS_FROM
// names.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The file written. */
const OUTPUT = join(import.meta.dirname, "..", "src", "rules", "limits.ts");

/** The table's last line: the clock, which `value_of` answers beside the table's limits. */
const CLOCK = "TICKS_PER_SECOND";

/** One constant: its name, its value as the engine writes it, and its comment's lines. */
interface Limit {
  readonly name: string;
  readonly value: string;
  readonly comment: readonly string[];
}

/** The names of the RULE_57 table, in its order. */
function tableNames(lines: readonly string[]): string[] {
  const start = lines.findIndex((line) => line.startsWith("pub const RULE_57:"));
  const end = lines.findIndex((line, at) => at > start && line === "];");
  if (start === -1 || end === -1) {
    throw new Error("the limits file has no RULE_57 table");
  }
  return lines.slice(start + 1, end).map((line) => {
    const named = /^ {4}\("([A-Z0-9_]+)",/u.exec(line);
    if (named?.[1] === undefined) {
      throw new Error(`a line of RULE_57 names no constant: ${line}`);
    }
    return named[1];
  });
}

/** The constant `name`: its plain integer value and the comment above it. */
function limitOf(lines: readonly string[], name: string): Limit {
  const at = lines.findIndex((line) => line.startsWith(`pub const ${name}: `));
  const declared = /^pub const [A-Z0-9_]+: [a-z0-9]+ = ([0-9_]+);$/u.exec(lines[at] ?? "");
  if (declared?.[1] === undefined) {
    throw new Error(`${name} has no plain integer value in the limits file`);
  }
  const comment: string[] = [];
  for (let above = at - 1; above >= 0 && (lines[above] ?? "").startsWith("///"); above -= 1) {
    // Rust's intra-document links, [`NAME`], are plain names here.
    comment.unshift((lines[above] ?? "").replace(/^\/\/\/ ?/u, "").replaceAll(/\[`([^`]+)`\]/gu, "`$1`"));
  }
  return { name, value: declared[1], comment };
}

/** The text of src/rules/limits.ts for the engine's `source`. */
function generated(source: string): string {
  const lines = source.split("\n");
  const limits = [...tableNames(lines), CLOCK].map((name) => limitOf(lines, name));
  const header = [
    "// The limits of a page's rule table (page-rules.md RULE-57, REQ-6608),",
    "// generated by scripts/limits.ts from the engine's",
    "// crates/neoteletext-rules/src/limits.rs, their one home, at the commit",
    "// scripts/check.sh names (LIMITS_FROM), which checks this copy against it.",
    "// Each keeps the engine's name: write a limit by its name, never its",
    "// figure. Do not edit this file; generate it.",
    "",
  ];
  const body = limits.flatMap(({ name, value, comment }) => [
    ...(comment.length === 1 ? [`/** ${comment[0] ?? ""} */`] : ["/**", ...comment.map((line) => ` * ${line}`.trimEnd()), " */"]),
    `export const ${name} = ${value};`,
  ]);
  return [...header, ...body, ""].join("\n");
}

const [path, mode] = process.argv.slice(2);
if (path === undefined || (mode !== undefined && mode !== "--check")) {
  throw new Error("usage: node scripts/limits.ts LIMITS_RS [--check]");
}
const text = generated(readFileSync(path, "utf8"));
if (mode === "--check") {
  if (readFileSync(OUTPUT, "utf8") !== text) {
    throw new Error("src/rules/limits.ts differs from what the engine's limits file gives: generate it again");
  }
} else {
  writeFileSync(OUTPUT, text);
}
