// Writes src/input/functional-keys.ts, every functional key's name at the
// place of its code, from the engine's neoteletext_input::keys, the one home
// of the codes (DOC-1936; the engine's REQ-204: one code for every key that
// is not a character, which never changes). The engine keeps two tables and
// computes a code from them (`keys::code`): codes below `FIRST_NAMED` are
// the places of `ONE_BYTE`, and codes from it are the names of `KEY_NAMES`
// that `ONE_BYTE` does not hold, in that table's order. This writes the one
// table those give, so that the kit holds no code as a figure.
//   node scripts/key-codes.ts SOURCES           write the file
//   node scripts/key-codes.ts SOURCES --check   fail when the file differs
// SOURCES is a folder holding the engine's files at the paths below;
// scripts/check.sh fills it from the engine's repository at the commit
// LIMITS_FROM names.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The file written. */
const OUTPUT = join(import.meta.dirname, "..", "src", "input", "functional-keys.ts");

/** The engine's files: the module that says where the remaining names begin, and its two tables. */
const KEYS = "crates/neoteletext-input/src/keys.rs";
const ONE_BYTE = "crates/neoteletext-input/src/keys/one_byte.rs";
const KEY_NAMES = "crates/neoteletext-input/src/names.rs";

/** The table `name` of the engine's file `path`: its strings in order, as many as its type declares. */
function tableOf(root: string, path: string, name: string): string[] {
  const lines = readFileSync(join(root, path), "utf8").split("\n");
  const start = lines.findIndex((line) => new RegExp(`^pub(?:\\(super\\))? const ${name}: \\[&str; [0-9]+\\] = \\[$`, "u").test(line));
  const end = lines.findIndex((line, at) => at > start && line === "];");
  const declared = /\[&str; ([0-9]+)\]/u.exec(lines[start] ?? "")?.[1];
  if (start === -1 || end === -1 || declared === undefined) {
    throw new Error(`${path} has no table ${name}`);
  }
  const names = lines.slice(start + 1, end).map((line) => {
    // One name a line, with a comment after some.
    const named = /^ {4}"([A-Za-z0-9]*)",(?: +\/\/.*)?$/u.exec(line);
    if (named?.[1] === undefined) {
      throw new Error(`a line of ${name} in ${path} is no name: ${line}`);
    }
    return named[1];
  });
  if (names.length !== Number(declared)) {
    throw new Error(`${name} in ${path} declares ${declared} names and lists ${names.length}`);
  }
  return names;
}

/** The engine's `FIRST_NAMED`: where the codes of the remaining W3C names begin. */
function firstNamed(root: string): number {
  const declared = /^pub const FIRST_NAMED: u32 = ([0-9]+);$/mu.exec(readFileSync(join(root, KEYS), "utf8"))?.[1];
  if (declared === undefined) {
    throw new Error(`${KEYS} has no FIRST_NAMED`);
  }
  return Number(declared);
}

/** Every functional key's name at the place of its code, "" at a code not in use, as the engine's `keys::code` numbers them. */
function namesByCode(root: string): string[] {
  const oneByte = tableOf(root, ONE_BYTE, "ONE_BYTE");
  const keyNames = tableOf(root, KEY_NAMES, "KEY_NAMES");
  if (oneByte.length !== firstNamed(root)) {
    throw new Error(`ONE_BYTE holds ${oneByte.length} codes, which is not where FIRST_NAMED says the remaining names begin`);
  }
  const names = [...oneByte, ...keyNames.filter((name) => !oneByte.includes(name))];
  const used = names.filter((name) => name !== "");
  if (new Set(used).size !== used.length) {
    throw new Error("a key is named twice in the engine's tables, so it would have two codes");
  }
  return names;
}

/** The text of src/input/functional-keys.ts for the engine's files under `root`. */
function generated(root: string): string {
  return [
    "// Every functional key's name at the place of its code (DOC-1936; the",
    "// engine's REQ-204), generated by scripts/key-codes.ts from the engine's",
    "// neoteletext_input::keys, the one home of the codes",
    `// (${KEYS},`,
    `// ${ONE_BYTE} and`,
    `// ${KEY_NAMES}), at the commit scripts/check.sh`,
    "// names (LIMITS_FROM), which checks this copy against them. The codes are",
    "// what the engine's `keys::code` answers: the places of `ONE_BYTE`, then,",
    "// from `FIRST_NAMED`, the names of `KEY_NAMES` that `ONE_BYTE` does not",
    "// hold, in that table's order. Read a code with `keyCode`, never as a",
    "// figure. Do not edit this file; generate it.",
    "",
    '/** The functional keys: the name at place `n` is the key of code `n`, and "" is a code not in use. */',
    "export const FUNCTIONAL_KEY_NAMES: readonly string[] = [",
    ...namesByCode(root).map((name) => `  ${JSON.stringify(name)},`),
    "];",
    "",
  ].join("\n");
}

const [root, mode] = process.argv.slice(2);
if (root === undefined || (mode !== undefined && mode !== "--check")) {
  throw new Error("usage: node scripts/key-codes.ts SOURCES [--check]");
}
const text = generated(root);
if (mode === "--check") {
  if (readFileSync(OUTPUT, "utf8") !== text) {
    throw new Error("src/input/functional-keys.ts differs from what the engine's key tables give: generate it again");
  }
} else {
  writeFileSync(OUTPUT, text);
}
